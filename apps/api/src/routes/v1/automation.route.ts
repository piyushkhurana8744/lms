import { Router } from 'express';
import { PERMISSIONS } from '@edtech/permissions';
import { AutomationController } from '../../controllers/automation.controller';
import { authenticate } from '../../middleware/auth.middleware';
import { ensureWorkspaceContext } from '../../middleware/tenant.middleware';
import { requirePermission } from '../../middleware/rbac.middleware';
const router:Router=Router(); router.use(authenticate,ensureWorkspaceContext);
router.get('/registry',requirePermission(PERMISSIONS.AUTOMATION_VIEW),AutomationController.registry);
router.get('/',requirePermission(PERMISSIONS.AUTOMATION_VIEW),AutomationController.list);
router.post('/',requirePermission(PERMISSIONS.AUTOMATION_CREATE),AutomationController.create);
router.get('/executions/:executionId',requirePermission(PERMISSIONS.AUTOMATION_EXECUTION_VIEW),AutomationController.execution);
router.post('/executions/:executionId/retry',requirePermission(PERMISSIONS.AUTOMATION_EXECUTION_RETRY),AutomationController.executionAction('retry'));
router.post('/executions/:executionId/cancel',requirePermission(PERMISSIONS.AUTOMATION_EXECUTION_CANCEL),AutomationController.executionAction('cancel'));
router.post('/executions/:executionId/replay',requirePermission(PERMISSIONS.AUTOMATION_REPLAY),AutomationController.executionAction('replay'));
router.get('/:id',requirePermission(PERMISSIONS.AUTOMATION_VIEW),AutomationController.get);
router.patch('/:id',requirePermission(PERMISSIONS.AUTOMATION_EDIT),AutomationController.update);
router.post('/:id/activate',requirePermission(PERMISSIONS.AUTOMATION_ACTIVATE),AutomationController.transition('activate'));
router.post('/:id/pause',requirePermission(PERMISSIONS.AUTOMATION_PAUSE),AutomationController.transition('pause'));
router.post('/:id/archive',requirePermission(PERMISSIONS.AUTOMATION_ARCHIVE),AutomationController.transition('archive'));
router.get('/:id/executions',requirePermission(PERMISSIONS.AUTOMATION_EXECUTION_VIEW),AutomationController.executions);
export default router;
